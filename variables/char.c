#include <stdio.h>

int main() {

    // char = character data type, used to store a single character (1 byte)

    char grade = 'A';
    char symbol = '?';
    char letter = 'Z';
    char currency = '$';

    printf("The grade is %c.\n", grade);
    printf("The symbol is %c.\n", symbol);
    printf("The letter is %c.\n", letter);
    printf("The currency is %c.\n", currency);

    return 0;
}